#!/usr/bin/env python3
"""Generate sql/04_cdc.sql: change-log table, consumer offset table and one trigger per source table.

Triggers record only (table, op, primary key). The CDC reader re-reads the current row, which
keeps the log narrow and makes applying changes idempotent (including replays after a crash).
"""
TABLES = {  # table -> primary key column
    "customer": "customer_id", "address": "address_id", "product": "product_id",
    "orders": "order_id", "order_item": "order_item_id", "payment": "payment_id",
    "interaction": "interaction_id", "loyalty_txn": "txn_id",
    "customer_score": "customer_id", "loyalty_tier_rule": "tier",
}

out = ["-- Generated by generate_cdc.py. Trigger-based CDC for Sybase ASE.", "use testdb", "go", ""]
out += [
    "if object_id('cdc_change_log') is not null drop table cdc_change_log",
    "go",
    "if object_id('cdc_offset') is not null drop table cdc_offset",
    "go",
    "",
    "-- One row per changed key per statement. change_id is the replication order.",
    "create table cdc_change_log (",
    "    change_id   numeric(18,0) identity,",
    "    table_name  varchar(30)   not null,",
    "    op          char(1)       not null,      -- I / U / D",
    "    pk_value    varchar(30)   not null,",
    "    change_ts   datetime      default getdate() not null,",
    "    constraint pk_cdc_change_log primary key (change_id)",
    ")",
    "go",
    "",
    "-- Consumer checkpoint: last change_id fully applied to the target.",
    "create table cdc_offset (",
    "    consumer        varchar(30)   not null,",
    "    last_change_id  numeric(18,0) not null,",
    "    updated_at      datetime      not null,",
    "    constraint pk_cdc_offset primary key (consumer)",
    ")",
    "go",
    "",
]
for t, pk in TABLES.items():
    ins = f"insert cdc_change_log (table_name, op, pk_value)"
    out += [
        f"if object_id('trg_cdc_{t}') is not null drop trigger trg_cdc_{t}",
        "go",
        f"create trigger trg_cdc_{t} on {t} for insert, update, delete as",
        "begin",
        f"    {ins}",
        f"    select '{t}', 'I', convert(varchar(30), i.{pk}) from inserted i",
        f"     where not exists (select 1 from deleted d where d.{pk} = i.{pk})",
        f"    {ins}",
        f"    select '{t}', 'U', convert(varchar(30), i.{pk}) from inserted i",
        f"     where exists (select 1 from deleted d where d.{pk} = i.{pk})",
        f"    {ins}",
        f"    select '{t}', 'D', convert(varchar(30), d.{pk}) from deleted d",
        f"     where not exists (select 1 from inserted i where i.{pk} = d.{pk})",
        "end",
        "go",
        "",
    ]
open("sql/04_cdc.sql", "w").write("\n".join(out))
print("wrote sql/04_cdc.sql")
