#!/usr/bin/env python3
"""Generate sql/04_cdc.sql: change-log table, consumer offset table and one row-level trigger per table.

Triggers log only (table, op, primary key). The reader re-reads the current row, so applying changes is idempotent.

Ordering/visibility: Oracle readers never block on uncommitted rows, so "WHERE change_id > last" could skip a change whose
transaction commits late. The log is created with ROWDEPENDENCIES so every row carries its own COMMIT SCN (ORA_ROWSCN);
the reader snapshots the current SCN and reads exactly the rows committed in (last_scn, snapshot_scn].
"""
TABLES = {  # table -> expression for the key, evaluated on :new / :old
    "airport": "{r}.iata", "flight": "to_char({r}.flight_id)",
    "flight_inventory": "{r}.flight_id || '|' || {r}.cabin",
    "booking": "to_char({r}.booking_id)", "booking_segment": "to_char({r}.segment_id)",
    "flight_event": "to_char({r}.event_id)", "compensation": "to_char({r}.segment_id)",
}
out = ["-- Generated by generate_cdc.py. Trigger-based CDC for Oracle.", "set define off", "",
 "begin",
 "  for t in (select table_name from user_tables where table_name in ('CDC_CHANGE_LOG','CDC_OFFSET')) loop",
 "    execute immediate 'drop table ' || t.table_name || ' purge';",
 "  end loop;",
 "end;", "/", "",
 "-- One row per changed key per change. ROWDEPENDENCIES: ORA_ROWSCN is the row's own commit SCN.",
 "create table cdc_change_log (",
 "  change_id   number generated always as identity primary key,",
 "  table_name  varchar2(30) not null,",
 "  op          char(1)      not null,            -- I / U / D",
 "  pk_value    varchar2(60) not null,",
 "  change_ts   timestamp    default sys_extract_utc(systimestamp) not null",
 ") rowdependencies;", "",
 "-- Consumer checkpoint: every log row committed at or before last_scn has been applied.",
 "create table cdc_offset (",
 "  consumer    varchar2(30) primary key,",
 "  last_scn    number       not null,",
 "  updated_at  timestamp    not null",
 ");", ""]
for t, key in TABLES.items():
    new, old = key.format(r=":new"), key.format(r=":old")
    out += [f"create or replace trigger trg_cdc_{t}",
            f"after insert or update or delete on {t} for each row",
            "begin",
            "  if inserting then",
            f"    insert into cdc_change_log (table_name, op, pk_value) values ('{t}', 'I', {new});",
            "  elsif updating then",
            f"    insert into cdc_change_log (table_name, op, pk_value) values ('{t}', 'U', {new});",
            "  else",
            f"    insert into cdc_change_log (table_name, op, pk_value) values ('{t}', 'D', {old});",
            "  end if;",
            "end;", "/", "show errors", ""]
open("sql/04_cdc.sql", "w").write("\n".join(out) + "\n")
print("wrote sql/04_cdc.sql")
