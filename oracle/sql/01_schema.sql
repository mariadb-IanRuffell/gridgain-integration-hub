-- Travel / reservations schema (Oracle). customer_id refers to the customer in the MariaDB CRM system:
-- there is deliberately NO foreign key (different system); the GridGain hub is where the two are joined.
whenever sqlerror continue
set define off

begin
  for t in (select table_name from user_tables where table_name in
            ('COMPENSATION','FLIGHT_EVENT','BOOKING_SEGMENT','BOOKING','FLIGHT_INVENTORY','FLIGHT','AIRPORT')) loop
    execute immediate 'drop table ' || t.table_name || ' cascade constraints purge';
  end loop;
end;
/

create table airport (
  iata     char(3)       primary key,
  name     varchar2(80)  not null,
  city     varchar2(60)  not null,
  country  char(2)       not null,
  tz       varchar2(40)
);

create table flight (
  flight_id      number(10)    generated by default as identity primary key,
  flight_no      varchar2(8)   not null,
  origin         char(3)       not null references airport,
  destination    char(3)       not null references airport,
  dep_time       timestamp     not null,
  arr_time       timestamp     not null,
  distance_km    number(6)     not null,
  aircraft       varchar2(10),
  status         varchar2(10)  default 'SCHEDULED' not null,   -- SCHEDULED / DELAYED / CANCELLED / DEPARTED / ARRIVED
  delay_minutes  number(4)     default 0 not null,
  constraint ck_flight_status check (status in ('SCHEDULED','DELAYED','CANCELLED','DEPARTED','ARRIVED'))
);
create index ix_flight_dep on flight (dep_time);

create table flight_inventory (
  flight_id        number(10)    not null references flight,
  cabin            varchar2(10)  not null,                      -- ECONOMY / BUSINESS / FIRST
  seats_total      number(4)     not null,
  seats_available  number(4)     not null,
  next_seat        number(4)     default 1 not null,            -- never decremented: seat numbers stay unique after cancellations
  base_fare        number(10,2)  not null,
  constraint pk_flight_inventory primary key (flight_id, cabin),
  constraint ck_inv_cabin check (cabin in ('ECONOMY','BUSINESS','FIRST')),
  constraint ck_inv_seats check (seats_available between 0 and seats_total)
);

create table booking (
  booking_id   number(10)    generated by default as identity primary key,
  booking_ref  char(6)       not null unique,
  customer_id  number(10)    not null,                          -- MariaDB customer.customer_id
  status       varchar2(10)  default 'CONFIRMED' not null,      -- CONFIRMED / CANCELLED
  booked_at    timestamp     default sys_extract_utc(systimestamp) not null,
  channel      varchar2(10)  default 'WEB' not null,
  total_fare   number(12,2)  default 0 not null,
  refunded     number(12,2)  default 0 not null,
  currency     char(3)       default 'AED' not null
);
create index ix_booking_customer on booking (customer_id);

create table booking_segment (
  segment_id      number(10)    generated by default as identity primary key,
  booking_id      number(10)    not null references booking,
  flight_id       number(10)    not null references flight,
  cabin           varchar2(10)  not null,
  seat_no         varchar2(4),
  passenger_name  varchar2(80)  not null,
  fare            number(10,2)  not null,
  status          varchar2(10)  default 'TICKETED' not null,    -- TICKETED / CHECKED_IN / FLOWN / CANCELLED
  miles_earned    number(8)     default 0 not null
);
create index ix_segment_booking on booking_segment (booking_id);
create index ix_segment_flight  on booking_segment (flight_id);

create table flight_event (
  event_id    number(10)     generated by default as identity primary key,
  flight_id   number(10)     not null references flight,
  event_type  varchar2(12)   not null,                           -- DELAY / CANCEL
  detail      varchar2(200),
  event_time  timestamp      default sys_extract_utc(systimestamp) not null
);

-- Output of sp_process_disruptions
create table compensation (
  segment_id  number(10)     primary key references booking_segment,
  amount      number(10,2)   not null,
  reason      varchar2(20)   not null,                           -- CANCELLED / DELAY_720 / DELAY_360 / DELAY_SHORT
  created_at  timestamp      not null
);
