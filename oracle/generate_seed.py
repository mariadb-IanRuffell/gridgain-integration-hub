#!/usr/bin/env python3
"""Generate sql/02_seed.sql: flights, seat inventory and bookings for the travel/reservations system.

Deterministic (seed=7) relative to the time it is run. Bookings use customer ids 1..250, the same ids as the MariaDB CRM
system, so the two datasets can be joined in the GridGain hub.
"""
import random
from datetime import datetime, timedelta, timezone

random.seed(7)
NOW = datetime.now(timezone.utc).replace(microsecond=0, tzinfo=None)
N_CUSTOMERS, N_BOOKINGS = 250, 650

AIRPORTS = [  # iata, name, city, country, tz, km from the DXB hub
    ("DXB", "Dubai International", "Dubai", "AE", "Asia/Dubai", 0),
    ("AUH", "Zayed International", "Abu Dhabi", "AE", "Asia/Dubai", 130),
    ("DOH", "Hamad International", "Doha", "QA", "Asia/Qatar", 380),
    ("RUH", "King Khalid International", "Riyadh", "SA", "Asia/Riyadh", 990),
    ("KHI", "Jinnah International", "Karachi", "PK", "Asia/Karachi", 1200),
    ("BOM", "Chhatrapati Shivaji Maharaj", "Mumbai", "IN", "Asia/Kolkata", 1930),
    ("DEL", "Indira Gandhi International", "Delhi", "IN", "Asia/Kolkata", 2200),
    ("CAI", "Cairo International", "Cairo", "EG", "Africa/Cairo", 2400),
    ("IST", "Istanbul Airport", "Istanbul", "TR", "Europe/Istanbul", 3000),
    ("FRA", "Frankfurt Airport", "Frankfurt", "DE", "Europe/Berlin", 4830),
    ("CDG", "Charles de Gaulle", "Paris", "FR", "Europe/Paris", 5240),
    ("LHR", "Heathrow", "London", "GB", "Europe/London", 5470),
    ("SIN", "Changi", "Singapore", "SG", "Asia/Singapore", 5840),
    ("JNB", "O. R. Tambo", "Johannesburg", "ZA", "Africa/Johannesburg", 6400),
    ("NRT", "Narita", "Tokyo", "JP", "Asia/Tokyo", 7940),
    ("JFK", "John F. Kennedy", "New York", "US", "America/New_York", 11000),
    ("SYD", "Kingsford Smith", "Sydney", "AU", "Australia/Sydney", 12040),
    ("LAX", "Los Angeles International", "Los Angeles", "US", "America/Los_Angeles", 13400),
]
CAB = {"ECONOMY": (300, 1.0, 1.0), "BUSINESS": (42, 3.0, 1.5), "FIRST": (8, 6.0, 2.0)}   # seats, fare x, miles x
FIRST = ["Aisha", "Omar", "Layla", "Khalid", "Fatima", "Yusuf", "Noor", "Hassan", "James", "Emma", "Oliver", "Sophia", "Priya",
         "Arjun", "Wei", "Mei", "Hiroshi", "Chloe", "Hugo", "Elena", "Marco", "Ivan", "Carlos", "Lucia", "Ahmed", "Sara"]
LAST = ["Haddad", "Rahman", "Khan", "Mansour", "Patel", "Singh", "Smith", "Brown", "Taylor", "Evans", "Chen", "Tanaka", "Dubois",
        "Rossi", "Novak", "Garcia", "Silva", "Ali", "Ibrahim", "Schmidt", "Wilson", "Roberts"]
DELAY_REASONS = ["technical inspection", "weather at destination", "late inbound aircraft", "air traffic control restrictions", "crew rotation"]
q = lambda s: "'" + s.replace("'", "''") + "'"
ts = lambda d: "timestamp '" + d.strftime("%Y-%m-%d %H:%M:%S") + "'"


def seat_no(cabin, n):   # must match fn_seat_no in 03_procs.sql
    base = {"FIRST": 1, "BUSINESS": 3, "ECONOMY": 12}[cabin]
    return f"{base + (n - 1) // 6}{'ABCDEF'[(n - 1) % 6]}"


out = ["-- Generated by generate_seed.py (deterministic, seed=7). Do not edit by hand.", "set define off", "set feedback off"]
emit = out.append

for iata, name, city, cc, tz, _ in AIRPORTS:
    emit(f"insert into airport values ({q(iata)}, {q(name)}, {q(city)}, {q(cc)}, {q(tz)});")

# ---- flights: every spoke in both directions, ~7 flights each over -45 d .. +60 d
flights, fid = [], 0
for idx, (iata, _, _, _, _, km) in enumerate(AIRPORTS[1:], start=1):
    for direction, (o, d) in enumerate([("DXB", iata), (iata, "DXB")]):
        for k in range(7):
            fid += 1
            dep = (NOW + timedelta(days=random.uniform(-45, 60))).replace(minute=random.choice([0, 15, 30, 45]), second=0)
            dur = timedelta(hours=km / 800 + 0.6)
            flights.append(dict(id=fid, no=f"XA{idx * 10 + direction}{k}", o=o, d=d, dep=dep, arr=dep + dur, km=km,
                                ac=random.choice(["A380", "B777", "A350"]), status="SCHEDULED", delay=0))
past = [f for f in flights if f["dep"] < NOW - timedelta(hours=6)]
for f in flights:
    if f["dep"] < NOW - timedelta(hours=6):
        f["status"] = "ARRIVED"
        if random.random() < 0.18:
            f["delay"] = random.choice([25, 40, 55, 90, 140, 200, 250, 370, 420, 760])
    elif f["dep"] < NOW:
        f["status"] = "DEPARTED"
future = [f for f in flights if f["dep"] > NOW + timedelta(days=1)]
random.shuffle(future)
for f in future[:8]:
    f["status"], f["delay"] = "DELAYED", random.choice([190, 240, 300, 420, 600, 800])
for f in future[8:11]:
    f["status"] = "CANCELLED"

inv = {}
for f in flights:
    emit(f"insert into flight (flight_id, flight_no, origin, destination, dep_time, arr_time, distance_km, aircraft, status, delay_minutes) values "
         f"({f['id']}, {q(f['no'])}, {q(f['o'])}, {q(f['d'])}, {ts(f['dep'])}, {ts(f['arr'])}, {f['km']}, {q(f['ac'])}, {q(f['status'])}, {f['delay']});")
    base = round(150 + f["km"] * 0.25, 2)
    for cab, (seats, fx, _) in CAB.items():
        inv[(f["id"], cab)] = dict(total=seats, avail=seats, nxt=1, fare=round(base * fx, 2))

# ---- bookings
by_route = {}
for f in flights:
    by_route.setdefault((f["o"], f["d"]), []).append(f)
weights = [1 / (r ** 0.6) for r in range(1, N_CUSTOMERS + 1)]
ids = list(range(1, N_CUSTOMERS + 1)); random.shuffle(ids)
refs, bookings, segs, sid = set(), [], [], 0
for bid in range(1, N_BOOKINGS + 1):
    cust = random.choices(ids, weights)[0]
    cabin = random.choices(list(CAB), [80, 17, 3])[0]
    out_f = random.choice(flights)
    legs = [out_f]
    r = random.random()
    if r < 0.45:
        back = [f for f in by_route.get((out_f["d"], out_f["o"]), []) if f["dep"] > out_f["dep"] + timedelta(days=2)]
        if back:
            legs.append(random.choice(back))
    elif r > 0.92:
        legs.append(random.choice(flights))
    first_dep = min(f["dep"] for f in legs)
    booked = min(first_dep - timedelta(days=random.uniform(3, 90)), NOW - timedelta(hours=1))
    cancelled = (all(f["dep"] > NOW + timedelta(days=4) and f["status"] == "SCHEDULED" for f in legs) and random.random() < 0.09)
    while True:
        ref = "".join(random.choices("ABCDEFGHJKLMNPQRSTUVWXYZ23456789", k=6))
        if ref not in refs:
            refs.add(ref); break
    pax = f"{random.choice(FIRST)} {random.choice(LAST)}"
    total = refund = 0.0
    for f in legs:
        sid += 1
        i = inv[(f["id"], cabin)]
        fare = i["fare"]; n = i["nxt"]; i["nxt"] += 1
        if cancelled:
            st, miles = "CANCELLED", 0
        else:
            i["avail"] -= 1
            st = ("FLOWN" if f["status"] in ("ARRIVED", "DEPARTED") else
                  "CHECKED_IN" if f["dep"] < NOW + timedelta(hours=24) and f["status"] != "CANCELLED" else "TICKETED")
            miles = round(f["km"] * CAB[cabin][2])
        total += fare
        segs.append(dict(id=sid, b=bid, f=f["id"], cabin=cabin, seat=seat_no(cabin, n), pax=pax, fare=fare, st=st, miles=miles))
    if cancelled:
        hours = (first_dep - NOW).total_seconds() / 3600
        refund = round(total * (0.9 if hours > 72 else 0.5 if hours > 24 else 0), 2)
    bookings.append(dict(id=bid, ref=ref, cust=cust, st="CANCELLED" if cancelled else "CONFIRMED", at=booked,
                         ch=random.choice(["WEB", "APP", "CALL", "AGENT"]), total=round(total, 2), refund=refund))

for (fid_, cab), i in inv.items():
    emit(f"insert into flight_inventory (flight_id, cabin, seats_total, seats_available, next_seat, base_fare) values "
         f"({fid_}, {q(cab)}, {i['total']}, {i['avail']}, {i['nxt']}, {i['fare']});")
for b in bookings:
    emit(f"insert into booking (booking_id, booking_ref, customer_id, status, booked_at, channel, total_fare, refunded, currency) values "
         f"({b['id']}, {q(b['ref'])}, {b['cust']}, {q(b['st'])}, {ts(b['at'].replace(microsecond=0))}, {q(b['ch'])}, {b['total']}, {b['refund']}, 'AED');")
for s in segs:
    emit(f"insert into booking_segment (segment_id, booking_id, flight_id, cabin, seat_no, passenger_name, fare, status, miles_earned) values "
         f"({s['id']}, {s['b']}, {s['f']}, {q(s['cabin'])}, {q(s['seat'])}, {q(s['pax'])}, {s['fare']}, {q(s['st'])}, {s['miles']});")
eid = 0
for f in flights:
    if f["status"] == "CANCELLED" or f["delay"] > 0:
        eid += 1
        detail = "Flight cancelled: " + random.choice(DELAY_REASONS) if f["status"] == "CANCELLED" else f"Delayed {f['delay']} min: " + random.choice(DELAY_REASONS)
        et = f["dep"] - timedelta(hours=random.uniform(1, 20))
        emit(f"insert into flight_event (event_id, flight_id, event_type, detail, event_time) values "
             f"({eid}, {f['id']}, {q('CANCEL' if f['status'] == 'CANCELLED' else 'DELAY')}, {q(detail)}, {ts(et.replace(microsecond=0))});")

emit("commit;")
for t, c in [("flight", "flight_id"), ("booking", "booking_id"), ("booking_segment", "segment_id"), ("flight_event", "event_id")]:
    emit(f"alter table {t} modify ({c} generated by default as identity (start with limit value));")

open("sql/02_seed.sql", "w").write("\n".join(out) + "\n")
nonc = [s for s in segs if s["st"] != "CANCELLED"]
print(f"airports={len(AIRPORTS)} flights={len(flights)} inventory={len(inv)} bookings={len(bookings)} segments={len(segs)} "
      f"events={eid} delayed={sum(f['status']=='DELAYED' for f in flights)} cancelled_flights={sum(f['status']=='CANCELLED' for f in flights)} "
      f"late_arrivals_180+={sum(f['status']=='ARRIVED' and f['delay']>=180 for f in flights)} cancelled_bookings={sum(b['st']=='CANCELLED' for b in bookings)} "
      f"active_segments={len(nonc)}")
