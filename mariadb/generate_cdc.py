#!/usr/bin/env python3
"""Generate sql/04_cdc.sql: change-log table, consumer offset table and row triggers for every replicated table.

Triggers record only (table, op, primary key). The CDC reader re-reads the current row, which keeps the log narrow and makes
applying changes idempotent (including replays after a crash).

Ordering: the reader polls "change_id > last". With plain AUTO_INCREMENT a transaction that took id 7 but commits after the one that
took id 8 would be skipped (InnoDB readers never wait for uncommitted rows). So ids come from a one-row counter table that every trigger
updates: the row lock is held until the writing transaction ends, which makes ids gapless and commit-ordered (a rollback gives the id
back). The price is that writing transactions serialise on that row (fine at this scale; a deadlock is possible when two transactions
touch the same rows in a different order, and InnoDB then rolls one back). For high write rates use the binlog instead (Debezium).
"""
TABLES = {  # table -> primary key column
    "customer": "customer_id", "address": "address_id", "product": "product_id",
    "orders": "order_id", "order_item": "order_item_id", "payment": "payment_id",
    "interaction": "interaction_id", "loyalty_txn": "txn_id",
    "customer_score": "customer_id", "loyalty_tier_rule": "tier",
}

out = [
    "-- Generated by generate_cdc.py. Trigger-based CDC for MariaDB.",
    "DROP TABLE IF EXISTS cdc_change_log, cdc_offset, cdc_seq;",
    "",
    "-- Gapless, commit-ordered change ids: the row lock on this counter is held until the writing transaction ends.",
    "CREATE TABLE cdc_seq (id TINYINT NOT NULL PRIMARY KEY, v BIGINT NOT NULL) ENGINE=InnoDB;",
    "INSERT INTO cdc_seq VALUES (1, 0);",
    "",
    "-- One row per changed key per row change. change_id is the replication order.",
    "CREATE TABLE cdc_change_log (",
    "    change_id   BIGINT       NOT NULL,",
    "    table_name  VARCHAR(30)  NOT NULL,",
    "    op          CHAR(1)      NOT NULL,      -- I / U / D",
    "    pk_value    VARCHAR(30)  NOT NULL,",
    "    change_ts   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),",
    "    PRIMARY KEY (change_id)",
    ") ENGINE=InnoDB;",
    "",
    "-- Consumer checkpoint: last change_id fully applied to the target.",
    "CREATE TABLE cdc_offset (",
    "    consumer        VARCHAR(30) NOT NULL,",
    "    last_change_id  BIGINT      NOT NULL,",
    "    updated_at      DATETIME    NOT NULL,",
    "    PRIMARY KEY (consumer)",
    ") ENGINE=InnoDB;",
    "",
    "DELIMITER //",
    "DROP PROCEDURE IF EXISTS cdc_log//",
    "CREATE PROCEDURE cdc_log(IN p_table VARCHAR(30), IN p_op CHAR(1), IN p_pk VARCHAR(30))",
    "BEGIN",
    "    DECLARE n BIGINT;",
    "    UPDATE cdc_seq SET v = v + 1 WHERE id = 1;          -- takes the lock and keeps it until commit",
    "    SELECT v INTO n FROM cdc_seq WHERE id = 1;           -- our own update is visible",
    "    INSERT INTO cdc_change_log (change_id, table_name, op, pk_value) VALUES (n, p_table, p_op, p_pk);",
    "END//",
    "DELIMITER ;",
    "",
]
for t, pk in TABLES.items():
    for suffix, event, op, row in (("ai", "INSERT", "I", "NEW"), ("au", "UPDATE", "U", "NEW"), ("ad", "DELETE", "D", "OLD")):
        out += [f"DROP TRIGGER IF EXISTS trg_cdc_{t}_{suffix};",
                f"CREATE TRIGGER trg_cdc_{t}_{suffix} AFTER {event} ON {t} FOR EACH ROW CALL cdc_log('{t}', '{op}', {row}.{pk});"]
    out.append("")
with open("sql/04_cdc.sql", "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote sql/04_cdc.sql")
